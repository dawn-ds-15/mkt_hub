CREATE OR REPLACE VIEW marketing.project_kpi_allocation_status AS
SELECT annual.id AS annual_plan_id,
       annual.year,
       annual_item.kpi_key,
       annual_item.target_value AS annual_target,
       COALESCE(sum(project_item.target_value), 0) AS projects_total,
       COALESCE(sum(project_item.target_value), 0) - annual_item.target_value AS difference,
       CASE
           WHEN COALESCE(sum(project_item.target_value), 0) = annual_item.target_value THEN 'BALANCED'
           WHEN COALESCE(sum(project_item.target_value), 0) < annual_item.target_value THEN 'UNDER_ALLOCATED'
           ELSE 'OVER_ALLOCATED'
       END AS allocation_status
FROM marketing.annual_kpi_plans AS annual
JOIN marketing.annual_kpi_plan_items AS annual_item ON annual_item.annual_plan_id = annual.id
LEFT JOIN marketing.project_kpi_plans AS project_plan ON project_plan.year = annual.year
LEFT JOIN marketing.project_kpi_plan_items AS project_item
       ON project_item.project_plan_id = project_plan.id
      AND project_item.kpi_key = annual_item.kpi_key
GROUP BY annual.id, annual.year, annual_item.kpi_key, annual_item.target_value;

