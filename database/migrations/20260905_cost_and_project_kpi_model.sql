CREATE OR REPLACE FUNCTION finance.prevent_expense_category_cycle()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.parent_id IS NULL THEN
        RETURN NEW;
    END IF;

    IF EXISTS (
        WITH RECURSIVE ancestors AS (
            SELECT category.id, category.parent_id
            FROM finance.expense_categories AS category
            WHERE category.id = NEW.parent_id
            UNION ALL
            SELECT category.id, category.parent_id
            FROM finance.expense_categories AS category
            JOIN ancestors ON category.id = ancestors.parent_id
        )
        SELECT 1 FROM ancestors WHERE id = NEW.id
    ) THEN
        RAISE EXCEPTION 'Expense category hierarchy cannot contain a cycle';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prevent_expense_category_cycle
    ON finance.expense_categories;

CREATE TRIGGER trg_prevent_expense_category_cycle
BEFORE INSERT OR UPDATE OF parent_id
ON finance.expense_categories
FOR EACH ROW
EXECUTE FUNCTION finance.prevent_expense_category_cycle();

