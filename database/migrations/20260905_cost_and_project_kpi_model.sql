CREATE OR REPLACE VIEW finance.expense_category_monthly_summary AS
WITH RECURSIVE category_paths AS (
    SELECT category.id AS ancestor_id, category.id AS descendant_id
    FROM finance.expense_categories AS category
    UNION ALL
    SELECT path.ancestor_id, child.id
    FROM category_paths AS path
    JOIN finance.expense_categories AS child ON child.parent_id = path.descendant_id
)
SELECT path.ancestor_id AS category_id,
       entry.project_id,
       extract(year FROM entry.expense_date)::smallint AS expense_year,
       extract(month FROM entry.expense_date)::smallint AS expense_month,
       entry.currency_id,
       sum(entry.planned_amount) AS planned_total,
       sum(entry.actual_amount) AS actual_total,
       count(*) AS source_entry_count
FROM category_paths AS path
JOIN finance.project_expense_entries AS entry ON entry.category_id = path.descendant_id
WHERE entry.deleted_at IS NULL
  AND entry.status IN ('SAVED', 'APPROVED')
GROUP BY path.ancestor_id, entry.project_id,
         extract(year FROM entry.expense_date), extract(month FROM entry.expense_date),
         entry.currency_id;

CREATE OR REPLACE VIEW finance.expense_category_yearly_summary AS
SELECT category_id, project_id, expense_year, currency_id,
       sum(planned_total) AS planned_total,
       sum(actual_total) AS actual_total,
       sum(planned_total) - sum(actual_total) AS remaining,
       CASE
           WHEN sum(planned_total) IS NULL OR sum(planned_total) = 0 THEN NULL
           ELSE round(sum(actual_total) / sum(planned_total) * 100, 4)
       END AS usage_percent,
       sum(source_entry_count) AS source_entry_count
FROM finance.expense_category_monthly_summary
GROUP BY category_id, project_id, expense_year, currency_id;

