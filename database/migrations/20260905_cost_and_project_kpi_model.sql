CREATE OR REPLACE FUNCTION marketing.touch_kpi_plan_from_item()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    parent_plan_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'annual_kpi_plan_items' THEN
        IF TG_OP = 'DELETE' THEN
            parent_plan_id := OLD.annual_plan_id;
        ELSE
            parent_plan_id := NEW.annual_plan_id;
        END IF;
        UPDATE marketing.annual_kpi_plans
        SET updated_at = CURRENT_TIMESTAMP
        WHERE id = parent_plan_id;
    ELSE
        IF TG_OP = 'DELETE' THEN
            parent_plan_id := OLD.project_plan_id;
        ELSE
            parent_plan_id := NEW.project_plan_id;
        END IF;
        UPDATE marketing.project_kpi_plans
        SET updated_at = CURRENT_TIMESTAMP
        WHERE id = parent_plan_id;
    END IF;
    RETURN NULL;
END;
$$;

